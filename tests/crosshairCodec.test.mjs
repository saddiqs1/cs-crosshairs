import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import test from 'node:test'
import ts from 'typescript'
import { decodeCrosshairShareCode, encodeCrosshair } from 'csgo-sharecode'

const require = createRequire(import.meta.url)
const source = readFileSync(
	new URL('../src/lib/crosshairCodec.ts', import.meta.url),
	'utf8'
)
const js = ts
	.transpileModule(source, {
		compilerOptions: {
			module: ts.ModuleKind.ESNext,
			target: ts.ScriptTarget.ES2020,
		},
	})
	.outputText.replaceAll(
		"'csgo-sharecode'",
		JSON.stringify(pathToFileURL(require.resolve('csgo-sharecode')).href)
	)
const { getCrosshairCommands } = await import(
	`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`
)
const oldCode = 'CSGO-obHU6-NLWyP-EtkUh-pywKV-TXQ3A'
const commandsFor = (code) =>
	Object.fromEntries(
		getCrosshairCommands(code)
			.split(';')
			.map((command) => {
				const [, name, value] = command.match(
					/^(\w+) "(-?\d+(?:\.\d+)?)"$/
				)
				return [name, Number(value)]
			})
	)

test('legacy codes produce current pixel dimensions, colors and command names', () => {
	const legacy = {
		...decodeCrosshairShareCode(oldCode),
		style: 4,
		length: 2,
		thickness: 0.5,
		gap: -2,
		color: 0,
		alphaEnabled: false,
	}
	const commands = commandsFor(encodeCrosshair(legacy))
	assert.equal(commands.cl_crosshair_length, 4)
	assert.equal(commands.cl_crosshair_thickness, 1)
	assert.equal(commands.cl_crosshair_gap, 3)
	assert.equal(commands.cl_crosshair_screen_height, 1080)
	assert.deepEqual(
		[
			commands.cl_crosshaircolor_r,
			commands.cl_crosshaircolor_g,
			commands.cl_crosshaircolor_b,
			commands.cl_crosshaircolor_a,
		],
		[255, 0, 0, 255]
	)
	const manager = readFileSync(
		new URL('../src/pages/manager.tsx', import.meta.url),
		'utf8'
	)
	for (const code of manager.match(/CSGO-[A-Za-z0-9-]+/g)) {
		assert.ok(Number.isFinite(commandsFor(code).cl_crosshair_length))
		assert.doesNotMatch(
			getCrosshairCommands(code),
			/cl_crosshairsize|cl_crosshairusealpha|cl_crosshairgap |\n/
		)
	}
})

test('September pixel codes retain their dimensions and original screen height', () => {
	const base = decodeCrosshairShareCode(
		'CSmruJvT2oNMbuQTnT7AxpUbmoAippt23rntOEkDXkT7wL'
	)
	for (const format of ['legacy-v3', 'legacy-v4']) {
		const commands = commandsFor(
			encodeCrosshair({
				...base,
				format,
				outlineMode: 2,
				outlineEnabled: true,
			})
		)
		assert.equal(commands.cl_crosshair_length, 2)
		assert.equal(commands.cl_crosshair_thickness, 2)
		assert.equal(commands.cl_crosshair_screen_height, 960)
		assert.equal(
			commands.cl_crosshair_drawoutline,
			format === 'legacy-v4' ? 2 : 1
		)
	}
})

test('donk CS2 code exports the actual static cross settings', () => {
	// Real game code supplied by the user, not generated by the codec under test.
	const code = 'CSmruJvT2oNMbuQTnT7AxpUbmoAippt23rntOEkDXkT7wL'
	const commands = commandsFor(code)
	assert.equal(commands.cl_crosshairstyle, 4)
	assert.equal(commands.cl_crosshair_gap, 1)
	assert.equal(commands.cl_crosshair_drawoutline, 0)
	assert.equal(commands.cl_crosshair_length, 2)
	assert.equal(commands.cl_crosshair_thickness, 2)
	assert.equal(commands.cl_crosshair_screen_height, 960)
	assert.deepEqual(
		[
			commands.cl_crosshaircolor_r,
			commands.cl_crosshaircolor_g,
			commands.cl_crosshaircolor_b,
		],
		[37, 255, 0]
	)
	// Size commands reset authored height in CS2, so restore it last.
	assert.match(
		getCrosshairCommands(code),
		/;cl_crosshair_screen_height "960"$/
	)
})

test('invalid codes are rejected', () => {
	for (const code of ['', 'junk', `junk${oldCode}`, `${oldCode}junk`])
		assert.throws(() => getCrosshairCommands(code))
})
